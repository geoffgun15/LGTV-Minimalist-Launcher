const { chromium } = require('playwright');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
 const browser = await chromium.launch(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {});
 try {
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 2 });
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const errors = [];page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
   window.launches = [];
   window.PalmServiceBridge = function () {this.cancel = function () {};this.call = function (uri, json) {if(uri.endsWith('/launch'))window.launches.push(JSON.parse(json).id);setTimeout(() => this.onservicecallback(JSON.stringify({returnValue:true,exist:true})),20);};};
  });
  const order = () => page.locator('#apps .tile').evaluateAll(tiles => tiles.map(tile => tile.dataset.id));
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('favorites')));
  const ready = () => page.waitForFunction(() => !document.getElementById('refresh').hasAttribute('aria-busy'));
  await page.goto(pathToFileURL(path.join(__dirname,'../app/index.html')).href);await ready();
  const initial=await order(),homeBox=await page.locator('[data-id="youtube.leanback.v4"]').boundingBox();
  await page.locator('#edit').click();
  assert(JSON.stringify(await order())===JSON.stringify(initial),'Edit preserves home app list and order');
  assert(JSON.stringify(homeBox)===JSON.stringify(await page.locator('[data-id="youtube.leanback.v4"]').boundingBox()),'Edit preserves tile position');
  assert(await page.locator('#reorder').count()===0,'No separate reorder mode');
  await page.keyboard.press('Enter');await page.keyboard.press('ArrowLeft');
  assert(JSON.stringify(await order())===JSON.stringify(initial),'First app cannot move before start');
  await page.keyboard.press('ArrowRight');assert((await order())[1]===initial[0],'Arrow moves picked app');
  assert(await page.evaluate(()=>document.activeElement.dataset.id)===initial[0],'Focus follows picked app');
  await page.keyboard.press('Enter');assert((await saved())[1]===initial[0],'OK persists order');
  const committed=await order();await page.keyboard.press('Enter');await page.keyboard.press('ArrowRight');await page.keyboard.press('Escape');
  assert(JSON.stringify(await order())===JSON.stringify(committed),'Back cancels current move');
  assert(await page.locator('#edit-tools').isVisible(),'Cancel stays in editing');
  await page.locator('#add-apps').click();assert(await page.locator('#section-title').textContent()==='Add apps','Add opens picker');
  assert(await page.locator('#input-section').isHidden(),'Picker hides unrelated inputs');
  await page.locator('[data-id="com.crunchyroll.webapp"]').click();await page.locator('[data-id="com.microsoft.xbox"]').click();
  assert(await page.locator('[data-id="com.microsoft.xbox"]').getAttribute('aria-pressed')==='true','Picker marks added apps');
  await page.keyboard.press('Escape');assert((await order()).length===committed.length+2,'Picker returns to updated favorites');
  assert(await page.evaluate(()=>document.activeElement.dataset.id)==='com.microsoft.xbox','Focus returns to last added app');
  assert(await page.locator('#input-section').isVisible(),'Home context returns');
  await page.locator('#remove-selected').click();assert(!(await order()).includes('com.microsoft.xbox'),'Remove affects highlighted app');
  await page.locator('[data-id="com.crunchyroll.webapp"]').click();await page.locator('#move-left').click();await page.locator('#place').click();
  const pointerOrder=await saved();await page.locator('#done-editing').click();
  assert(await page.locator('#normal-tools').isVisible(),'Done returns directly home');
  assert(JSON.stringify(await order())===JSON.stringify(pointerOrder),'Home keeps edited order');
  await page.reload();await ready();assert(JSON.stringify(await order())===JSON.stringify(pointerOrder),'Order survives reload');
  await page.evaluate(()=>localStorage.setItem('favorites',JSON.stringify(window.C4_CATALOG.apps.slice(0,10).map(app=>app.id))));
  await page.reload();await ready();const multirow=await order();await page.locator('#edit').click();await page.keyboard.press('Enter');
  for(let step=0;step<7;step++)await page.keyboard.press('ArrowRight');
  assert((await order())[7]===multirow[0],'Move crosses wrapped row');await page.keyboard.press('Enter');await page.keyboard.press('Escape');
  assert(await page.locator('#normal-tools').isVisible(),'Back exits editing without intermediate screen');
  await page.locator('#settings').click();assert(await page.evaluate(()=>launches.includes('com.palm.app.settings')),'Native settings launch');
  assert(await page.evaluate(()=>launches.length)===1,'Editing never launches apps');
  await page.evaluate(()=>localStorage.setItem('favorites','[]'));await page.reload();await ready();await page.locator('#edit').click();
  assert(await page.locator('#remove-selected').isDisabled(),'Empty favorites disable remove');
  assert(await page.evaluate(()=>document.activeElement.id)==='add-apps','Empty editing focuses Add apps');
  await page.locator('#add-apps').click();await page.locator('[data-id="netflix"]').click();await page.locator('#picker-done').click();await page.locator('#remove-selected').click();
  assert((await order()).length===0,'Can remove last favorite');assert(await page.evaluate(()=>document.activeElement.id)==='add-apps','Last removal focuses Add apps');
  assert(errors.length===0,'No JavaScript errors: '+errors.join(', '));
  console.log('PASS: inline home editing, stable layout, move/save/cancel, add picker, focus return, remove, empty states, settings');
 } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
